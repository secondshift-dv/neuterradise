    public const string LanguageKey = "app.uiLanguage";
    public static event EventHandler? LanguageChanged;
    public static string CurrentLanguage { get; private set; } = AppConfiguration.EnglishLanguage;

    public static readonly IReadOnlyList<string> SupportedLanguages = [AppConfiguration.EnglishLanguage, AppConfiguration.IndonesianLanguage];

    public static string Get(string key, string fallback)
    {
        if (LocalizationTables.TryGet(CurrentLanguage, key, out var tabled))
        {
            return tabled;
        }

        if (string.Equals(CurrentLanguage, AppConfiguration.IndonesianLanguage, StringComparison.OrdinalIgnoreCase))
        {
            if (IndonesianStrings.TryGetValue(key, out var idVal)) return idVal;
        }
        else
        {
            if (EnglishStrings.TryGetValue(key, out var enVal)) return enVal;
        }

        return fallback;
    }

    public static string Get(string key) => Get(key, key);

    public static string Format(string key, string formatFallback, params object[] args)
    {
        var format = Get(key, formatFallback);
        return string.Format(CultureInfo.CurrentUICulture, format, args);
    }

    public static bool ApplyLanguage(string? languageCode)
    {
        var normalized = languageCode?.Trim().ToLowerInvariant();
        if (normalized is not (AppConfiguration.EnglishLanguage or AppConfiguration.IndonesianLanguage))
            normalized = AppConfiguration.EnglishLanguage;

        var changed = !string.Equals(CurrentLanguage, normalized, StringComparison.Ordinal);
        CurrentLanguage = normalized;

        var culture = CultureInfo.GetCultureInfo(normalized == AppConfiguration.IndonesianLanguage ? "id-ID" : "en-US");
        CultureInfo.CurrentUICulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
        Thread.CurrentThread.CurrentUICulture = culture;


        if (changed)
        {
            LanguageChanged?.Invoke(null, EventArgs.Empty);
        }
        return changed;
    }

    public static IReadOnlyDictionary<string, string> GetStrings(string languageCode)
    {
        var normalized = languageCode?.Trim().ToLowerInvariant();
        return normalized == AppConfiguration.IndonesianLanguage ? IndonesianStrings : EnglishStrings;
    }

    public static void ValidateRequiredKeys(string languageCode, IEnumerable<string> requiredKeys, Action<string>? diagnostic = null)
    {
        ArgumentNullException.ThrowIfNull(requiredKeys);
        foreach (var key in requiredKeys)
            if (!LocalizationTables.TryGet(languageCode, key, out _) && !GetStrings(languageCode).ContainsKey(key))
                diagnostic?.Invoke($"Missing localization key: {key}");
    }

